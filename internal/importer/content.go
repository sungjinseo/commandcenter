// maxLoggedFailures is how many asset failures per repository are logged
// one by one; the rest are counted (the report keeps maxRepoErrors).
const maxLoggedFailures = 20

// finalizeTimeout bounds the metadata rebuilds that run after a stop.
const finalizeTimeout = 5 * time.Minute

// assetKind is what the content loop does with a source asset.
type assetKind int

const (
	kindIngest    assetKind = iota
	kindGenerated           // generated by Command Center (checksums, metadata, indexes): skipped without download
	kindForeign             // not part of the format's layout (a Maven .index/, archetype-catalog.xml): skipped with a note
)

// downloadSlack is how much a download may exceed the size the source lists.
const downloadSlack = 1 << 20

// repoRun is the state of one repository's content import.
type repoRun struct {
	e     *Engine
	c     *nexus.Client
	p     Params
	pl    *plan
	rp    *repo.Repository // nil in a dry run of a repository that would be created
	actor string
	log   Logger
	prog  *Progress
	rep   *Report

	mu       sync.Mutex
	counts   Counts
	logged   int
	foreign  int
	gas      map[string]bool // maven: GA directories to rebuild
	packages map[string]bool // npm: packages whose tags to apply
}

func (r *repoRun) add(f func(c *Counts)) {
	r.mu.Lock()
	f(&r.counts)
	r.mu.Unlock()
}

func (r *repoRun) fail(a nexus.Asset, err error) {
	msg := a.Path + ": " + logsafe.Err(err)
	if repo.IsIngestConflict(err) {
		r.rep.conflict(r.pl.src.Name + ": " + msg)
	}
	r.mu.Lock()
	r.counts.Failed++
	r.pl.rr.addError(msg)
	n := r.logged
	r.logged++
	r.mu.Unlock()
	r.prog.AssetsFailed.Add(1)
	if n < maxLoggedFailures {
		r.log.Errorf("%s: %s", r.pl.src.Name, msg)
	}
}

// importRepo imports the content of one hosted repository.
func (e *Engine) importRepo(ctx context.Context, c *nexus.Client, p Params, pl *plan, actor string, log Logger, prog *Progress, rep *Report) error {
	r := &repoRun{e: e, c: c, p: p, pl: pl, actor: actor, log: log, prog: prog, rep: rep,
		gas: map[string]bool{}, packages: map[string]bool{}}
	r.rp = e.Repos.Get(pl.target)
	if r.rp == nil || r.rp.Type != "hosted" || r.rp.Format != pl.format {
		if !p.DryRun {
			return fmt.Errorf("the target repository %q is not a %s hosted repository", pl.target, pl.format)
		}
		r.rp = nil // would be created: nothing to compare with
	}
	log.Infof("%s: importing content into %s", pl.src.Name, pl.target)

	work := make(chan nexus.Asset)
	var wg sync.WaitGroup
	n := p.Concurrency
	if n < 1 {
		n = DefaultConcurrency
	}
	for range n {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for a := range work {
				r.importAsset(ctx, a)
			}
		}()
	}
	listErr := c.Assets(ctx, pl.src.Name, func(a nexus.Asset) error {
		r.add(func(c *Counts) { c.Assets++ })
		prog.AssetsTotal.Add(1)
		send, err := r.classify(ctx, a)
		if err != nil || !send {
			return err
		}
		select {
		case work <- a:
			return nil
		case <-ctx.Done():
			return ctx.Err()
		}
	})
	close(work)
	wg.Wait()

	if !p.DryRun {
		r.finalize(ctx)
	}
	r.mu.Lock()
	pl.rr.Counts = r.counts
	r.mu.Unlock()
	cnt := pl.rr.Counts
	if p.DryRun {
		log.Infof("%s: %d assets listed: %d would be imported (%d bytes), %d already done, %d generated here (skipped)",
			pl.src.Name, cnt.Assets, cnt.WouldImport, cnt.Bytes, cnt.AlreadyDone, cnt.Skipped)
	} else {
		log.Infof("%s: %d assets listed: imported %d (%d bytes), skipped %d, failed %d, already done %d, earlier failures not retried %d",
			pl.src.Name, cnt.Assets, cnt.Imported, cnt.Bytes, cnt.Skipped, cnt.Failed, cnt.AlreadyDone, cnt.NotRetried)
		if r.logged > maxLoggedFailures {
			log.Errorf("%s: %d more assets failed (see the report)", pl.src.Name, r.logged-maxLoggedFailures)
		}
		if cnt.NotRetried > 0 {
			log.Warnf("%s: %d assets failed in an earlier run of job %s; start it again with retryFailed to retry them", pl.src.Name, cnt.NotRetried, p.Job)
		}
	}
	if listErr != nil {
		if ctx.Err() != nil {
			return ctx.Err()
		}
		return fmt.Errorf("listing the assets: %w", listErr)
	}
	return nil
}

// kind classifies a source asset by format.
func (r *repoRun) kind(a nexus.Asset) assetKind {
	p := a.Path
	switch r.pl.format {
	case "maven":
		mp, err := maven.ParsePath(p)
		switch {
		case err == nil && (mp.Hash != "" || mp.Metadata || strings.Contains(mp.Main, "maven-metadata.xml")):
			return kindGenerated
		case err != nil || mp.Coords == nil:
			return kindForeign
		}
	case "npm":
		if !strings.HasSuffix(p, ".tgz") || !strings.Contains(p, "/-/") {
			return kindGenerated // the packument: rebuilt from the tarballs
		}
	case "pypi":
		if !strings.HasPrefix(p, "packages/") || strings.HasSuffix(p, ".metadata") || strings.HasSuffix(p, ".asc") {
			return kindGenerated // index pages, PEP 658 metadata, signatures
		}
	case "cargo":
		if _, _, ok := crateOf(a); !ok {
			return kindGenerated // the sparse index and config.json
		}
	}
	return kindIngest
}

// crateOf returns the crate name and version of a .crate asset: from the
// asset's cargo attributes, else from its path "crates/{name}/{version}/download".
func crateOf(a nexus.Asset) (name, vers string, ok bool) {
	segs := strings.Split(a.Path, "/")
	if len(segs) != 4 || segs[0] != "crates" || segs[3] != "download" {
		return "", "", false
	}
	name, vers = segs[1], segs[2]
	if a.Cargo != nil && a.Cargo.Name != "" && a.Cargo.Version != "" {
		name, vers = a.Cargo.Name, a.Cargo.Version
	}
	return name, vers, name != "" && vers != ""
}

// npmPackage returns the package name of a tarball asset.
func npmPackage(a nexus.Asset) string {
	n, _ := npmNameVersion(a)
	return n
}

// npmNameVersion returns the package name and version the source says a
// tarball asset holds: its npm attributes, else the path
// "<name>/-/<base>-<version>.tgz" (scoped names included). The version is
// empty when neither gives it.
func npmNameVersion(a nexus.Asset) (name, version string) {
	pathName, rest, _ := strings.Cut(a.Path, "/-/")
	name = pathName
	if base := path.Base(pathName); strings.HasSuffix(rest, ".tgz") && strings.HasPrefix(rest, base+"-") {
		version = strings.TrimSuffix(strings.TrimPrefix(rest, base+"-"), ".tgz")
	}
	if a.Npm != nil {
		if a.Npm.Name != "" {
			name = a.Npm.Name
		}
		if a.Npm.Version != "" {
			version = a.Npm.Version
		}
	}
	return name, version
}

// gaDir returns the GA directory ("com/ex/app") of a Maven asset.
func gaDir(a nexus.Asset) string {
	mp, err := maven.ParsePath(a.Path)
	if err != nil || mp.Coords == nil {
		return ""
	}
	return strings.ReplaceAll(mp.Coords.GroupID, ".", "/") + "/" + mp.Coords.ArtifactID
}

// remember notes what finalize must do for an asset that is in the target.
func (r *repoRun) remember(a nexus.Asset) {
	r.mu.Lock()
	defer r.mu.Unlock()
	switch r.pl.format {
	case "maven":
		if ga := gaDir(a); ga != "" {
			r.gas[ga] = true
		}
	case "npm":
		if name := npmPackage(a); name != "" {
			r.packages[name] = true
		}
	}
}

// classify decides, before any download, whether an asset is sent to the
// workers: generated files and assets an earlier run of the job handled are
// counted here.
func (r *repoRun) classify(ctx context.Context, a nexus.Asset) (bool, error) {
	switch r.kind(a) {
	case kindGenerated:
		r.add(func(c *Counts) { c.Skipped++ })
		r.prog.AssetsSkipped.Add(1)
		return false, nil
	case kindForeign:
		r.mu.Lock()
		r.counts.Skipped++
		r.foreign++
		if r.foreign <= maxLoggedFailures {
			r.pl.rr.Notes = appendCapped(r.pl.rr.Notes, a.Path+": skipped: not a Maven artifact path")
		}
		r.mu.Unlock()
		r.prog.AssetsSkipped.Add(1)
		return false, nil
	}
	st, sha1, err := r.e.DB.ImportState(ctx, r.p.Job, r.pl.src.Name, a.Path)
	switch {
	case errors.Is(err, meta.ErrNotFound):
	case err != nil:
		return false, err
	// A state recorded without a sha1 is not trusted once the source
	// reports one: the asset is verified again.
	case (st == meta.ImportDone || st == meta.ImportSkipped) && (a.Checksum.SHA1 == "" || strings.EqualFold(sha1, a.Checksum.SHA1)):
		r.add(func(c *Counts) { c.AlreadyDone++ })
		r.prog.AssetsSkipped.Add(1)
		r.remember(a)
		return false, nil
	case st == meta.ImportFailed && !r.p.RetryFailed:
		r.add(func(c *Counts) { c.NotRetried++ })
		r.prog.AssetsFailed.Add(1)
		return false, nil
	}
	if r.p.DryRun {
		if r.identicalInTarget(ctx, a) {
			r.add(func(c *Counts) { c.WouldSkip++ })
		} else {
			r.add(func(c *Counts) { c.WouldImport++; c.Bytes += max(a.FileSize, 0) })
		}
		return false, nil
	}
	// Maven paths are the same in the target: an identical file there is
	// skipped, a different one is a conflict, both without downloading.
	if r.pl.format == "maven" {
		if cur, err := r.e.DB.GetAsset(ctx, r.rp.Name, a.Path); err == nil {
			switch {
			case a.Checksum.SHA256 != "" && strings.EqualFold(cur.BlobSHA256, a.Checksum.SHA256),
				a.Checksum.SHA256 == "" && a.Checksum.SHA1 != "" && strings.EqualFold(cur.SHA1, a.Checksum.SHA1):
				r.record(ctx, a, meta.ImportSkipped, "")
				r.add(func(c *Counts) { c.Skipped++ })
				r.prog.AssetsSkipped.Add(1)
				r.remember(a)
			case a.Checksum.SHA256 != "" || a.Checksum.SHA1 != "":
				err := repo.IngestConflict("%s already exists with different content", a.Path)
				r.record(ctx, a, meta.ImportFailed, err.Error())
				r.fail(a, err)
			default:
				return true, nil
			}
			return false, nil
		}
	}
	return true, nil
}

// identicalInTarget is the dry run's cheap check, on target metadata only:
// the same Maven path with the same checksum, or (other formats, whose keys
// are their own) a file with the same sha256 already in the target.
func (r *repoRun) identicalInTarget(ctx context.Context, a nexus.Asset) bool {
	if r.rp == nil {
		return false
	}
	if r.pl.format == "maven" {
		cur, err := r.e.DB.GetAsset(ctx, r.rp.Name, a.Path)
		return err == nil && (a.Checksum.SHA256 != "" && strings.EqualFold(cur.BlobSHA256, a.Checksum.SHA256) ||
			a.Checksum.SHA256 == "" && a.Checksum.SHA1 != "" && strings.EqualFold(cur.SHA1, a.Checksum.SHA1))
	}
	if a.Checksum.SHA256 == "" {
		return false
	}
	used, err := r.e.DB.BlobInUseInRepos(ctx, strings.ToLower(a.Checksum.SHA256), []string{r.rp.Name})
	return err == nil && used
}

func (r *repoRun) record(ctx context.Context, a nexus.Asset, status, errText string) {
	if len(errText) > 1000 {
		errText = strings.ToValidUTF8(errText[:1000], "")
	}
	if err := r.e.DB.SetImportState(context.WithoutCancel(ctx), r.p.Job, r.pl.src.Name, a.Path, strings.ToLower(a.Checksum.SHA1), status, errText); err != nil {
		r.log.Warnf("%s: could not record the state of %s: %v", r.pl.src.Name, a.Path, err)
	}
}

// errInternal is what a panicking asset records: the details (redacted)
// and the stack go to the server log only.
var errInternal = errors.New("internal error (see the server log)")

// downloadCap is the size cap of a download: min(listed size + downloadSlack,
// the server's upload limit) when the limit is set; when the source lists no
// size, the limit. byLimit tells that the upload limit is the cap.
func (r *repoRun) downloadCap(a nexus.Asset) (limit int64, byLimit bool) {
	var upload int64
	if r.e.MaxUpload != nil {
		upload = r.e.MaxUpload()
	}
	switch {
	case a.FileSize > 0 && (upload <= 0 || a.FileSize+downloadSlack < upload):
		return a.FileSize + downloadSlack, false
	case upload > 0:
		return upload, true
	case a.FileSize > 0:
		return a.FileSize + downloadSlack, false
	}
	return 0, false
}

// countingReader counts the bytes read into the run's counters.
type countingReader struct {
	r     io.Reader
	n     *int64
	total *atomic.Int64
	wrap  func(error) error // maps a read error (not io.EOF); nil keeps it
}

func (c *countingReader) Read(p []byte) (int, error) {
	n, err := c.r.Read(p)
	*c.n += int64(n)
	c.total.Add(int64(n))
	if err != nil && err != io.EOF && c.wrap != nil {
		err = c.wrap(err)
	}
	return n, err
}

// capError explains a download that passed its cap when the cap was the
// server's upload limit (byLimit): such a file needs a larger maxUploadMiB.
// Other errors are returned as they are.
func (r *repoRun) capError(err error, limit int64, byLimit bool) error {
	var ne *nexus.Error
	if !byLimit || !errors.As(err, &ne) || ne.Kind != nexus.ErrTooLarge {
		return err
	}
	return fmt.Errorf("the file is larger than maxUploadMiB (%d MiB); raise maxUploadMiB to import it: %w", limit>>20, err)
}

// importAsset downloads one asset (its checksum verified while streaming)
// into the format's ingester and records the outcome. An asset interrupted
// by a stop is not recorded, so a resume imports it.
func (r *repoRun) importAsset(ctx context.Context, a nexus.Asset) {
	if ctx.Err() != nil {
		return
	}
	defer func() {
		if r.e.afterAsset != nil {
			r.e.afterAsset(a.Path)
		}
	}()
	var n int64
	res, err := func() (res repo.IngestResult, err error) {
		// A panic fails this asset only; the job goes on.
		defer func() {
			if p := recover(); p != nil {
				r.e.log().Error("import: panic while importing an asset", "repository", r.pl.src.Name, "path", a.Path,
					"panic", logsafe.URLs(fmt.Sprint(p)), "stack", string(debug.Stack()))
				res, err = "", errInternal
			}
		}()
		// A cargo index line is fetched before the crate.
		var line []byte
		if r.pl.format == "cargo" {
			name, vers, _ := crateOf(a)
			l, err := r.c.CargoIndexLine(ctx, r.pl.src.Name, name, vers)
			if err != nil {
				return "", err
			}
			line = l.Raw
		}
		limit, byLimit := r.downloadCap(a)
		body, err := r.c.DownloadCapped(ctx, a, limit)
		if err != nil {
			return "", r.capError(err, limit, byLimit)
		}
		defer body.Close()
		in := &countingReader{r: body, n: &n, total: &r.prog.Bytes, wrap: func(err error) error { return r.capError(err, limit, byLimit) }}
		if r.e.ingestOverride != nil {
			return r.e.ingestOverride(ctx, r.rp, a, in)
		}
		switch r.pl.format {
		case "maven":
			return r.e.Maven.Ingest(ctx, r.rp, a.Path, in, r.actor)
		case "npm":
			wantName, wantVersion := npmNameVersion(a)
			_, res, err := r.e.Npm.Ingest(ctx, r.rp, wantName, wantVersion, in, r.actor)
			return res, err
		case "pypi":
			return r.e.Pypi.Ingest(ctx, r.rp, path.Base(a.Path), in, strings.ToLower(a.Checksum.SHA256), r.actor)
		case "cargo":
			return r.e.Cargo.Ingest(ctx, r.rp, in, bytes.TrimSpace(line), r.actor)
		}
		return "", fmt.Errorf("format %s has no ingester", r.pl.format)
	}()
	r.add(func(c *Counts) { c.Bytes += n })
	if err != nil {
		if ctx.Err() != nil {
			return
		}
		r.record(ctx, a, meta.ImportFailed, logsafe.Err(err))
		r.fail(a, err)
		return
	}
	if res == repo.Skipped {
		r.record(ctx, a, meta.ImportSkipped, "")
		r.add(func(c *Counts) { c.Skipped++ })
		r.prog.AssetsSkipped.Add(1)
	} else {
		r.record(ctx, a, meta.ImportDone, "")
		r.add(func(c *Counts) { c.Imported++ })
		r.prog.AssetsDone.Add(1)
	}
	r.remember(a)
}

// finalize rebuilds the Maven metadata of every GA that has files in the
// target (also after a stop, so what is in is usable) and, unless stopped,
// applies the npm dist-tags and deprecations of every imported package.
func (r *repoRun) finalize(ctx context.Context) {
	name := r.pl.src.Name
	switch r.pl.format {
	case "maven":
		if r.e.Maven == nil {
			return
		}
		fctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), finalizeTimeout)
		defer cancel()
		n, failed := 0, 0
		for ga := range r.gas {
			if err := r.e.Maven.RebuildGA(fctx, r.rp, ga); err != nil {
				failed++
				r.pl.rr.addError("rebuilding the metadata of " + ga + ": " + logsafe.Err(err))
				if failed <= maxLoggedFailures {
					r.log.Errorf("%s: rebuilding the metadata of %s: %v", name, ga, err)
				}
				continue
			}
			n++
		}
		r.log.Infof("%s: rebuilt maven-metadata.xml of %d GAs", name, n)
		if failed > 0 {
			r.add(func(c *Counts) { c.Failed += int64(failed) })
			r.prog.AssetsFailed.Add(int64(failed))
		}
	case "npm":
		if ctx.Err() != nil || r.e.Npm == nil {
			return // applied by the resume
		}
		tags, deps, failed := 0, 0, 0
		for pkg := range r.packages {
			if ctx.Err() != nil {
				return
			}
			pk, err := r.c.NpmPackument(ctx, name, pkg)
			if err == nil {
				var tr npm.TagResult
				tr, err = r.e.Npm.ApplyTags(ctx, r.rp, pkg, pk.DistTags, pk.Deprecated, r.actor)
				tags += tr.Tags
				deps += tr.Deprecated
				for _, s := range tr.Kept {
					r.pl.rr.Notes = appendCapped(r.pl.rr.Notes, pkg+": "+s)
				}
				for _, s := range tr.Skipped {
					r.pl.rr.Notes = appendCapped(r.pl.rr.Notes, pkg+": not applied: "+s)
				}
			}
			if err != nil {
				if ctx.Err() != nil {
					return
				}
				failed++
				r.pl.rr.addError("dist-tags of " + pkg + ": " + logsafe.Err(err))
				if failed <= maxLoggedFailures {
					r.log.Errorf("%s: dist-tags and deprecations of %s: %v", name, pkg, err)
				}
			}
		}
		r.log.Infof("%s: applied %d dist-tags and %d deprecations to %d packages", name, tags, deps, len(r.packages)-failed)
		if failed > 0 {
			r.add(func(c *Counts) { c.Failed += int64(failed) })
			r.prog.AssetsFailed.Add(int64(failed))
		}
	}
}

func appendCapped(list []string, s string) []string {
	if len(list) >= maxRepoErrors {
		return list
	}
	return append(list, s)
}
