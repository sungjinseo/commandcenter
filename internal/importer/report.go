package importer

import (
	"fmt"
	"sync"
	"sync/atomic"
	"time"
)

// Job states.
const (
	StatusRunning = "running"
	StatusOK      = "ok"
	StatusFailed  = "failed"
	StatusStopped = "stopped" // stopped on request or by a shutdown; resumable
	StatusDryRun  = "dry-run"
)

// Definition outcomes of one repository.
const (
	DefCreated     = "created"
	DefExists      = "exists"       // a repository with the same name, format and type is reused
	DefWouldCreate = "would-create" // dry run
	DefConflict    = "conflict"     // same name, different format or type: skipped
	DefMissing     = "missing"      // importDefinitions off and no such repository
	DefFailed      = "failed"
	DefSkipped     = "skipped"
)

// Caps of the lists in a report.
const (
	maxRepoErrors = 50
	maxConflicts  = 200
	maxWarnings   = 200
)

// Counts are the asset counts of a repository or of the whole job.
type Counts struct {
	Assets      int64 `json:"assets"`      // listed on the source
	Imported    int64 `json:"imported"`    // stored by this run
	Skipped     int64 `json:"skipped"`     // identical in the target, or generated by Command Center (checksums, metadata)
	Failed      int64 `json:"failed"`      // failed in this run
	AlreadyDone int64 `json:"alreadyDone"` // imported or skipped by an earlier run of the job
	NotRetried  int64 `json:"notRetried"`  // failed in an earlier run; retryFailed retries them
	WouldImport int64 `json:"wouldImport"` // dry run
	WouldSkip   int64 `json:"wouldSkip"`   // dry run: an identical file is in the target already
	Bytes       int64 `json:"bytes"`       // downloaded (dry run: the size that would be)
}

func (c *Counts) add(o Counts) {
	c.Assets += o.Assets
	c.Imported += o.Imported
	c.Skipped += o.Skipped
	c.Failed += o.Failed
	c.AlreadyDone += o.AlreadyDone
	c.NotRetried += o.NotRetried
	c.WouldImport += o.WouldImport
	c.WouldSkip += o.WouldSkip
	c.Bytes += o.Bytes
}

// RepoReport is one source repository in the report.
type RepoReport struct {
	Source     string   `json:"source"`
	Target     string   `json:"target"`
	Format     string   `json:"format"` // the source format (maven2, npm, ...)
	Type       string   `json:"type"`
	Definition string   `json:"definition"`        // Def* value
	Content    bool     `json:"content"`           // content was (or would be) imported
	Counts     Counts   `json:"counts"`            //
	Errors     []string `json:"errors,omitempty"`  // capped at maxRepoErrors
	Omitted    int      `json:"omitted,omitempty"` // errors beyond the cap
	Notes      []string `json:"notes,omitempty"`
}

func (r *RepoReport) addError(msg string) {
	if len(r.Errors) < maxRepoErrors {
		r.Errors = append(r.Errors, msg)
		return
	}
	r.Omitted++
}

// Unsupported lists the source repositories of a format this version does
// not import.
type Unsupported struct {
	Format       string   `json:"format"`
	Count        int      `json:"count"`
	Repositories []string `json:"repositories"`
	Note         string   `json:"note,omitempty"` // why and what to do instead, when there is more to say
}

// Report is the result of an import job, stored with the job.
type Report struct {
	Job      string    `json:"job"`
	Source   string    `json:"source"`
	DryRun   bool      `json:"dryRun"`
	Status   string    `json:"status"`
	Message  string    `json:"message,omitempty"`
	Started  time.Time `json:"started"`
	Finished time.Time `json:"finished,omitzero"`

	Repositories              []*RepoReport `json:"repositories"`
	Unsupported               []Unsupported `json:"unsupported"`
	ProxiesNeedingCredentials []string      `json:"proxiesNeedingCredentials"`
	Conflicts                 []string      `json:"conflicts"`
	ConflictsOmitted          int           `json:"conflictsOmitted,omitempty"`
	Warnings                  []string      `json:"warnings"`
	NotImported               []string      `json:"notImported"`
	Totals                    Counts        `json:"totals"`
	Created                   int           `json:"created"` // repositories created (dry run: would be)

	mu sync.Mutex
}

func newReport(job, source string, dry bool, now time.Time) *Report {
	return &Report{Job: job, Source: source, DryRun: dry, Status: StatusRunning, Started: now,
		Repositories: []*RepoReport{}, Unsupported: []Unsupported{}, ProxiesNeedingCredentials: []string{},
		Conflicts: []string{}, Warnings: []string{},
		NotImported: []string{
			"users, roles and privileges: the source API does not expose password hashes and its privilege model differs; recreate them by hand",
			"proxy remote credentials: the source API does not return them; enter them again on the listed proxies",
			"proxy caches: cached content refills on demand",
		}}
}

func (r *Report) conflict(msg string) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if len(r.Conflicts) < maxConflicts {
		r.Conflicts = append(r.Conflicts, msg)
		return
	}
	r.ConflictsOmitted++
}

func (r *Report) warn(msg string) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if len(r.Warnings) < maxWarnings {
		r.Warnings = append(r.Warnings, msg)
	}
}

// Summary is a one-line summary for the task run.
func (r *Report) Summary() string {
	t := r.Totals
	if r.DryRun {
		return fmt.Sprintf("dry run of job %s: %d repositories would be created, %d assets (%d bytes) would be imported, %d are identical in the target, %d already done; %d conflicts",
			r.Job, r.Created, t.WouldImport, t.Bytes, t.WouldSkip, t.AlreadyDone, len(r.Conflicts)+r.ConflictsOmitted)
	}
	return fmt.Sprintf("job %s: created %d repositories; imported %d assets (%d bytes), skipped %d, failed %d, already done %d; %d conflicts",
		r.Job, r.Created, t.Imported, t.Bytes, t.Skipped, t.Failed+t.NotRetried, t.AlreadyDone, len(r.Conflicts)+r.ConflictsOmitted)
}

// Progress holds the live counters of a running job (Decision 6).
type Progress struct {
	Job     string
	DryRun  bool
	Started time.Time

	ReposTotal, ReposDone                                atomic.Int64
	AssetsTotal, AssetsDone, AssetsSkipped, AssetsFailed atomic.Int64
	Bytes                                                atomic.Int64

	mu      sync.Mutex
	current string
}

func (p *Progress) setCurrent(s string) {
	p.mu.Lock()
	p.current = s
	p.mu.Unlock()
}

// ProgressView is a snapshot of Progress, as the API serves it.
type ProgressView struct {
	Job               string    `json:"job"`
	DryRun            bool      `json:"dryRun"`
	Started           time.Time `json:"started"`
	Repository        string    `json:"repository"`
	RepositoriesTotal int64     `json:"repositoriesTotal"`
	RepositoriesDone  int64     `json:"repositoriesDone"`
	AssetsTotal       int64     `json:"assetsTotal"`
	AssetsDone        int64     `json:"assetsDone"`
	AssetsSkipped     int64     `json:"assetsSkipped"`
	AssetsFailed      int64     `json:"assetsFailed"`
	Bytes             int64     `json:"bytes"`
}

// View snapshots the counters.
func (p *Progress) View() ProgressView {
	p.mu.Lock()
	cur := p.current
	p.mu.Unlock()
	return ProgressView{Job: p.Job, DryRun: p.DryRun, Started: p.Started, Repository: cur,
		RepositoriesTotal: p.ReposTotal.Load(), RepositoriesDone: p.ReposDone.Load(),
		AssetsTotal: p.AssetsTotal.Load(), AssetsDone: p.AssetsDone.Load(), AssetsSkipped: p.AssetsSkipped.Load(),
		AssetsFailed: p.AssetsFailed.Load(), Bytes: p.Bytes.Load()}
}
