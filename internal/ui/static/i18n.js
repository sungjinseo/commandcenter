const DICTS = { ko, en };
const KEY = "commandcenter.lang";
const listeners = [];

// storedLang returns the language chosen in this browser, or null.
function storedLang() {
  let v = null;
  try { v = localStorage.getItem(KEY); } catch (e) { /* private window */ }
  return v === "ko" || v === "en" ? v : null;
}

function initial() {
  const v = storedLang();
  if (v) return v;
  // Plan 10 Decision 5: an English browser gets English, everything else Korean.
  const nav = (navigator.language || "").toLowerCase();
  return nav.startsWith("en") ? "en" : "ko";
}

let lang = initial();
document.documentElement.lang = lang;

export const getLang = () => lang;
// locale is the Intl locale for numbers and dates in the current language.
export const locale = () => (lang === "ko" ? "ko-KR" : "en-US");

// setLang switches the language, remembers it and tells the listeners
// (the shell re-renders the current route).
export function setLang(l) {
  if (!Object.prototype.hasOwnProperty.call(DICTS, l) || l === lang) return;
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem(KEY, l); } catch (e) { /* private window */ }
  for (const fn of listeners) fn(l);
}

// applyServerDefault switches to the server's defaultLanguage (from
// /-/api/me) when the browser has no stored choice (plan 12 Decision 5). It
// does not store it, so a later change of the setting still applies; a
// stored choice always wins. It tells the listeners, which re-render.
export function applyServerDefault(l) {
  if (storedLang()) return false;
  if ((l !== "ko" && l !== "en") || l === lang) return false;
  lang = l;
  document.documentElement.lang = l;
  for (const fn of listeners) fn(l);
  return true;
}

export function onLangChange(fn) { listeners.push(fn); }

// t looks a key up in the current language, falling back to English and
// then to the key itself, and replaces "{name}" with params.name. When
// params.n is 1 and "<key>.1" exists, that singular form is used.
export function t(key, params) {
  const d = DICTS[lang];
  if (params && String(params.n) === "1" && Object.prototype.hasOwnProperty.call(d, key + ".1")) key += ".1";
  let s = Object.prototype.hasOwnProperty.call(d, key) ? d[key]
    : Object.prototype.hasOwnProperty.call(en, key) ? en[key] : key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m));
  return s;
}
