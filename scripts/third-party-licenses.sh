#!/usr/bin/env bash
# Writes THIRD_PARTY_LICENSES.txt: the full license, notice and patent files of every
# module linked into the commandcenter binary, plus the Go standard library's.
# BSD and MIT ask binary distributions to carry these texts; the Docker image copies the file.
# It runs in the Dockerfile's golang image, so the Go version it names is the one releases link.
# Usage: scripts/third-party-licenses.sh          (regenerate)
#        scripts/third-party-licenses.sh --check  (fail if the file is out of date; CI runs this)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && (pwd -W 2>/dev/null || pwd))"
out="$(cd "$(dirname "$0")/.." && pwd)/THIRD_PARTY_LICENSES.txt"
image="$(sed -n 's/^FROM .*\(golang:[^ ]*\).*/\1/p' "$(dirname "$0")/../Dockerfile")"
: "${image:?no golang FROM line in the Dockerfile}"

gen() {
  MSYS_NO_PATHCONV=1 docker run --rm \
    -v "$root:/src" -w /src \
    -v commandcenter-gocache:/root/.cache/go-build \
    -v commandcenter-gomod:/go/pkg/mod \
    -e CGO_ENABLED=0 \
    "$image" sh -c '
set -e
emit() { # emit <title> <dir>
  for f in $(ls "$2" | grep -iE "^(licen[cs]e|copying|notice|patents)([-._].*)?$" | sort); do
    printf "\n================================================================================\n"
    printf "%s — %s\n" "$1" "$f"
    printf "================================================================================\n\n"
    cat "$2/$f"
  done
}
echo "Third-party licenses for the commandcenter binary"
echo "Generated by scripts/third-party-licenses.sh from the modules linked into ./cmd/commandcenter."
echo "Command Center itself is MIT OR Apache-2.0: see LICENSE-MIT, LICENSE-APACHE and NOTICE."
emit "Go standard library ($(go env GOVERSION))" "$(go env GOROOT)"
# -buildvcs=false: on Linux and CI root in this container does not own the checkout, so git
# refuses to read it. The assignment fails the script when go list fails, instead of dropping
# every module.
mods="$(go list -buildvcs=false -deps -f "{{with .Module}}{{if .Version}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}" ./cmd/commandcenter)"
printf "%s\n" "$mods" | sort -u | while read -r path ver dir; do emit "$path $ver" "$dir"; done
'
}

if [ "${1:-}" = "--check" ]; then
  tmp="$(mktemp)"
  gen | tr -d '\r' >"$tmp"
  if ! diff -q "$tmp" <(tr -d '\r' <"$out") >/dev/null; then
    rm -f "$tmp"
    echo "THIRD_PARTY_LICENSES.txt is out of date: run scripts/third-party-licenses.sh" >&2
    exit 1
  fi
  rm -f "$tmp"
  echo "THIRD_PARTY_LICENSES.txt is up to date"
else
  gen | tr -d '\r' >"$out"
  echo "wrote $out"
fi
